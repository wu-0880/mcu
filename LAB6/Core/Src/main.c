void Process_Audio(uint16_t start)
{
    uint16_t max_val = 0;
    uint16_t min_val = 4095;

    // 計算 128 筆 ADC 的最大值與最小值
    for (uint16_t i = start; i < start + HALF_SIZE; i++)
    {
        if (adc_buf[i] > max_val)
        {
            max_val = adc_buf[i];
        }

        if (adc_buf[i] < min_val)
        {
            min_val = adc_buf[i];
        }
    }

    // 音量 = 最大值 - 最小值
    volume = max_val - min_val;

    latest_adc = adc_buf[start + HALF_SIZE - 1];    // 開機前 1 秒測量環境噪音
    if (!calibrated)
    {
        if (volume > noise)
        {
            noise = volume;
        }

        if (HAL_GetTick() - calibration_start >= 1000)
        {
            threshold = noise * 3 + 10;
            calibrated = 1;
        }

        return;
    }
    // 新增：紅燈門檻開關
    if (volume >= red_threshold)
    {
        HAL_GPIO_WritePin(GPIOC, GPIO_PIN_6, GPIO_PIN_SET);
    }
    else
    {
        HAL_GPIO_WritePin(GPIOC, GPIO_PIN_6, GPIO_PIN_RESET);
    }

    // 聲音越大，目標亮度越高

    if (volume <= threshold)
    {
        target_duty = 0;
    }
    else if (volume >= threshold * 4)
    {
        target_duty = 1000;
    }
    else
    {
        target_duty =
            (volume - threshold) * 1000 /
            (threshold * 3);
    }




}
