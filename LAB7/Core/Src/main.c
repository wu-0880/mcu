void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM6)
    {
        uint16_t value = 2048;

        if (wave_mode == 0)
        {
            // 正弦波：使用原本建立的100點查表
            value = sine_table[index_wave];
        }
        else if (wave_mode == 1)
        {
            // 三角波
            if (index_wave < 25)
                value = 2048 + 72 * index_wave;
            else if (index_wave < 75)
                value = 3848 - 72 * (index_wave - 25);
            else
                value = 248 + 72 * (index_wave - 75);
        }
        else
        {
            // 方波
            if (index_wave < 50)
                value = 3848;
            else
                value = 248;
        }

        HAL_DAC_SetValue(&hdac1,
                         DAC_CHANNEL_1,
                         DAC_ALIGN_12B_R,
                         value);

        index_wave++;

        if (index_wave >= 100)
            index_wave = 0;
    }
}
